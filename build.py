def ErrExit(errStr):
	print(errStr)
	sys.exit(-1)


def Execute(cmd):
	print(cmd)
	p = subprocess.Popen(cmd)
	p.wait()
	return p.returncode

def ExecuteOnErrQuit(cmd):
	print(cmd)
	p = subprocess.Popen(cmd)
	p.wait()
	if p.returncode:
		print("Error occured, while execute the following command")
		ErrExit(cmd)


FIELD_PATTERN = r"(#define\s*{0}\s*)(\d+)"

def GetFeildIntValueInFile(fileName, fieldName):
	fi = open(fileName)
	ftext = fi.read();
	fi.close()
	fieldPattern = FIELD_PATTERN.format(fieldName)
	ptn = re.compile(fieldPattern)
	m = ptn.search(ftext)
	if m is None:
		ErrExit(r"Can't find pattern " + fieldPattern + " in file: " + fileName)
	return int(m.groups()[1])

def increaseFeildIntValueInFile(fileName, fieldName):
	fi = open(fileName)
	ftext = fi.read();
	fi.close()
	fieldPattern = FIELD_PATTERN.format(fieldName)
	ptn = re.compile(fieldPattern)
	m = ptn.search(ftext)
	if m is None:
		ErrExit(r"Can't find pattern " + fieldPattern + " in file: " + fileName)

	value = int(m.groups()[1]) + 1
	data = ftext[:m.start()] + m.groups()[0] + str(value) + ftext[m.end():]

	fi = open(fileName, "w")
	fi.write(data);
	fi.close()

	return value

def VersionStr(*args):
	listStr = []
	for i in args:
		listStr.append(str(i))
	return ".".join(listStr)

def signFile(fileName):
	if cfg_no_sign:
		print("Ignore sign file:", fileName)
		return
	ext = os.path.splitext(fileName)[1].lower()
	if ext != '.dll' and ext != '.exe':
		return

	# Only sign exe or dll file
	code = -1
	for _ in range(3):
		cmdLine = r'signtool sign /d Crintsoft /du http://www.crintsoft.com /t  http://timestamp.verisign.com/scripts/timstamp.dll "{0}"'.format(fileName)
		code = Execute(cmdLine)
		if code != 0:
			time.sleep(2)
		else:
			return

	ErrExit("Failed to sign file: " + fileName)
	
def signFilesInDir(dir):
	for f in os.listdir(dir):
		signFile(os.path.join(dir, f))


def zipCode(ZipIncludeDir):
	# Compress source code to src.7z
	ZipExcludeExt = [ "", "rar", "ncb", "svn", "aps", "opt", "plg", "user", "scc", 
		"tmp", "obj", "idb", "pdb", "lib", "pch", "res", "exp", "stt", "zip", 
		"gz", "suo" ]

	ZipOutFile = "src.7z"
	ZipSrcCmd = ZipExe + " a -t7z " + ZipOutFile + " -i!".join(ZipIncludeDir) + " -xr!*.".join(ZipExcludeExt)
	if os.access(ZipOutFile, 0):
		os.remove(ZipOutFile)
	ExecuteOnErrQuit(ZipSrcCmd)
	print(ZipSrcCmd)

