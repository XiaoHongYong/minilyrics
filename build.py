def ErrExit(errStr):
	print(errStr)
	sys.exit(-1)


def Execute(cmd):
	print(cmd)
	p = subprocess.Popen(cmd)
	p.wait()


def ExecuteOnErrQuit(cmd):
	print(cmd)
	p = subprocess.Popen(cmd)
	p.wait()
	if p.returncode:
		print("Error occured, while execute the following command")
		ErrExit(cmd)

def GetFeildIntValueInFile(fileName, fieldPattern):
	fi = open(fileName)
	ftext = fi.read();
	ptn = re.compile(fieldPattern)
	m = ptn.search(ftext)
	if m is None:
		ErrExit(r"Can't find pattern " + fieldPattern + " in file: " + fileName)
	return int(m.groups()[0])
	
def VersionStr(*args):
	listStr = []
	for i in args:
		listStr.append(str(i))
	return ".".join(listStr)


